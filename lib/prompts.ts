/**
 * 填充 Prompt 模板中的 {占位符}。
 * 用法：fill(sceneGeneratorPrompt, { scene_type: "humor", recent_scenes: "..." })
 */
export function fillPrompt(
  template: string,
  vars: Record<string, string>
): string {
  return Object.entries(vars).reduce(
    (acc, [key, value]) => acc.split(`{${key}}`).join(value),
    template
  );
}

